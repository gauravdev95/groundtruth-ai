"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { Bell, CheckCheck } from "lucide-react";
import { AuthShell } from "@/components/auth/AuthShell";
import { RequireAuth } from "@/components/auth/RequireAuth";
import {
  fetchNotifications,
  fetchUnreadCount,
  markAllNotificationsRead,
  markNotificationRead,
  type NotificationItem,
} from "@/lib/api";

/**
 * Phase 7 notifications inbox. Rows are written only by the real flows
 * (application stage change, new message, assessment/interview updates) —
 * this page reads them, shows the unread count, and marks them read.
 */
function NotificationsContent() {
  const [items, setItems] = useState<NotificationItem[] | null>(null);
  const [unread, setUnread] = useState(0);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  async function load() {
    try {
      const [list, count] = await Promise.all([
        fetchNotifications(),
        fetchUnreadCount(),
      ]);
      setItems(list);
      setUnread(count.unread);
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Could not load notifications.",
      );
    }
  }

  useEffect(() => {
    void load();
  }, []);

  async function onMarkAllRead() {
    setBusy(true);
    try {
      await markAllNotificationsRead();
      await load();
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Could not mark notifications read.",
      );
    } finally {
      setBusy(false);
    }
  }

  async function onOpen(item: NotificationItem) {
    if (!item.is_read) {
      try {
        await markNotificationRead(item.id);
        setItems((prev) =>
          prev
            ? prev.map((n) => (n.id === item.id ? { ...n, is_read: true } : n))
            : prev,
        );
        setUnread((u) => Math.max(0, u - 1));
      } catch {
        // Marking read is best-effort; the link still works.
      }
    }
  }

  return (
    <AuthShell
      wide
      side={
        <Link href="/account" className="st-btn st-btn-outline st-btn-sm">
          Back to account
        </Link>
      }
    >
      <p className="st-eyebrow">Notifications</p>
      <h1 className="st-title">
        Your <span className="blue">updates.</span>
      </h1>
      <p className="st-sub">
        Application updates, new messages, and assessment news — generated by
        the real flows, never invented.{" "}
        {unread > 0 ? (
          <strong>
            {unread} unread.
          </strong>
        ) : (
          "You're all caught up."
        )}
      </p>

      {error ? (
        <div className="st-empty">
          <h2>Couldn&apos;t load notifications</h2>
          <p>{error}</p>
          <button
            type="button"
            className="st-btn st-btn-blue"
            onClick={() => window.location.reload()}
          >
            Try again
          </button>
        </div>
      ) : items === null ? (
        <div className="st-loading" role="status" aria-label="Loading">
          <span className="st-spinner" aria-hidden="true" />
          <p>Loading notifications…</p>
        </div>
      ) : items.length === 0 ? (
        <div className="st-empty">
          <Bell size={28} aria-hidden="true" />
          <h2>No notifications yet</h2>
          <p>
            When a recruiter moves your application, messages you, or an
            assessment report is ready, it will show up here.
          </p>
        </div>
      ) : (
        <>
          <div style={{ margin: "18px 0 12px", display: "flex", justifyContent: "flex-end" }}>
            <button
              type="button"
              className="st-btn st-btn-outline st-btn-sm"
              onClick={onMarkAllRead}
              disabled={busy || unread === 0}
            >
              <CheckCheck size={15} aria-hidden="true" /> Mark all read
            </button>
          </div>
          <div className="st-list">
            {items.map((item) => (
              <div
                key={item.id}
                className="st-list-item"
                style={
                  item.is_read
                    ? undefined
                    : { borderColor: "#1e2bda", background: "#f6f6ff" }
                }
              >
                <div style={{ flex: 1, minWidth: 0 }}>
                  <h3>{item.title}</h3>
                  <p className="st-list-meta">{item.body}</p>
                  <p className="st-list-meta">
                    {new Date(item.created_at).toLocaleString("en-IN", {
                      day: "numeric",
                      month: "short",
                      hour: "2-digit",
                      minute: "2-digit",
                    })}
                    {!item.is_read ? " · Unread" : ""}
                  </p>
                </div>
                {item.link ? (
                  <Link
                    href={item.link}
                    className="st-btn st-btn-outline st-btn-sm"
                    onClick={() => void onOpen(item)}
                  >
                    View
                  </Link>
                ) : (
                  <button
                    type="button"
                    className="st-btn st-btn-outline st-btn-sm"
                    onClick={() => void onOpen(item)}
                    disabled={item.is_read}
                  >
                    Mark read
                  </button>
                )}
              </div>
            ))}
          </div>
        </>
      )}
    </AuthShell>
  );
}

export default function NotificationsPage() {
  return (
    <RequireAuth>
      <NotificationsContent />
    </RequireAuth>
  );
}
